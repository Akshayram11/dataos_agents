MODEL (
  name sales3.products,
  kind FULL,
  cron '*/10 * * * *',
  grain product_id,
  description 'Product dimension table with full refresh on each run',
  tags ('product', 'dimension', 'catalog'),
  terms ('product.catalog', 'product.inventory'),
  assertions (
    unique_values(columns := (product_id))
  ),
  columns (
    product_id VARCHAR(10),
    product_name VARCHAR(100),
    category VARCHAR(50),
    subcategory VARCHAR(50),
    brand VARCHAR(50),
    color VARCHAR(20),
    size VARCHAR(20),
    weight NUMBER(10,2),
    material VARCHAR(50),
    model_number VARCHAR(50),
    sku VARCHAR(50),
    upc VARCHAR(20),
    price NUMBER(10,2),
    cost NUMBER(10,2),
    supplier VARCHAR(100),
    warranty_period VARCHAR(50),
    release_date DATE,
    rating NUMBER(3,1),
    stock_quantity NUMBER(38,0),
    discontinued BOOLEAN
  ),
  column_descriptions (
    product_id = 'Unique identifier for each product',
    product_name = 'Product name',
    category = 'Product category (Electronics, Home, Clothing, Sports, Food, Toys)',
    subcategory = 'Product subcategory',
    brand = 'Product brand name',
    color = 'Product color',
    size = 'Product size (xs, s, m, l, xl, OneSize)',
    weight = 'Product weight',
    material = 'Product material (Metal, Plastic, Wood, Fabric, Glass)',
    model_number = 'Product model number',
    sku = 'Stock keeping unit code',
    upc = 'Universal product code',
    price = 'Product selling price',
    cost = 'Product cost price',
    supplier = 'Product supplier name',
    warranty_period = 'Product warranty period',
    release_date = 'Product release date',
    rating = 'Product rating (1.0-5.0)',
    stock_quantity = 'Current stock quantity available',
    discontinued = 'Whether product is discontinued (0=active, 1=discontinued)'
  ),
  column_tags (
    product_id = ('identifier', 'primary_key', 'grain'),
    product_name = ('dimension', 'descriptive'),
    category = ('dimension', 'classification'),
    subcategory = ('dimension', 'classification'),
    brand = ('dimension', 'classification'),
    color = ('dimension', 'attribute'),
    size = ('dimension', 'attribute'),
    weight = ('measure', 'physical'),
    material = ('dimension', 'attribute'),
    model_number = ('identifier', 'reference'),
    sku = ('identifier', 'reference'),
    upc = ('identifier', 'reference'),
    price = ('measure', 'monetary'),
    cost = ('measure', 'monetary'),
    supplier = ('dimension', 'classification'),
    warranty_period = ('dimension', 'attribute'),
    release_date = ('temporal', 'date'),
    rating = ('measure', 'metric'),
    stock_quantity = ('measure', 'count', 'inventory'),
    discontinued = ('dimension', 'status')
  ),
  column_terms (
    product_id = ('entity.identifier', 'product.id'),
    category = ('product.classification', 'catalog.category'),
    price = ('product.price', 'revenue.metric'),
    cost = ('product.cost', 'expense.metric'),
    stock_quantity = ('product.inventory', 'supply.metric')
  )
);

SELECT
  product_id,
  product_name,
  category,
  subcategory,
  brand,
  color,
  size,
  weight,
  material,
  model_number,
  sku,
  upc,
  price,
  cost,
  supplier,
  warranty_period,
  release_date,
  rating,
  stock_quantity,
  discontinued
FROM raw.raw_products
